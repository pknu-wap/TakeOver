def export_review(data, path):
    output = ['# 이벤트 대사·엔딩 개정 원고', '', '현재 실행 대본은 Tools/StoryExpansion의 dialogue_revision.py, story_polish.py, ending_scenes.py에서 생성한다.', '']
    for event in data['campaign'] + data['general']:
        output += ['## ' + event['eventId'] + ' — ' + event.get('title', ''), '']
        for variant in [event] + event.get('companyVariants', []):
            if variant is not event:
                output += ['### ' + variant['title'], '']
            if variant.get('description'):
                output += [variant['description'], '']
            for choice in variant.get('choices', []):
                output += ['- 선택: ' + (choice.get('choiceText') or '(선택 없이 대화 진행)'),
                           '  - 주인공: ' + choice.get('playerLine', ''), '  - 상대: ' + choice.get('resultDialogue', '')]
    output += ['', '# 배드엔딩 원고', '']
    for number, ending in enumerate(data['plan']['endings'], start=1):
        output += [f"## 엔딩 {number}: {ending['title']} ({ending['signal']})", '']
        output += [str(i + 1) + '. ' + line['text'] for i, line in enumerate(ending['lines'])] + ['']
    path.write_text('\n'.join(output) + '\n', encoding='utf-8')
