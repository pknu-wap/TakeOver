    assert len(endings) == len(SCENES) == 14
    for index, (ending, paragraphs) in enumerate(zip(endings, SCENES)):
        # Three acts: missed opportunity, company decision, departure. No actors or percentages.
        ending['lines'] = []
        for i, text in enumerate(paragraphs):
            scene = (0 if index in (0, 2, 3, 4, 8, 9, 10) else 3) if i < 2 else 1 if i < 6 else 2
            pieces = re.split(r'(?<=[.!?])\s+', text, maxsplit=1) if i < 6 else [text]
            ending['lines'].extend({'narration': True, 'text': piece, 'scene': scene} for piece in pieces)
        assert len(ending['lines']) >= 13  # All indices from previous ending saves remain valid.
    return endings
