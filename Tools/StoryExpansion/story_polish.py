def apply_general_cards(events):
    for event in events:
        key = event["eventId"]
        event["title"], event["description"] = GENERAL_CARDS[key]
        for variant in event.get("companyVariants", []):
            variant["title"], variant["description"] = VARIANT_CARDS[key][variant["companyId"]]
    return events


def expand_campaign_story(events, *, legacy=False):
    for event in events:
        key = event["eventId"]
        event["title"], event["description"] = LEGACY_CARDS.get(key, CAMPAIGN_CARDS[key]) if legacy else CAMPAIGN_CARDS[key]
        opening = event["openingLines"]
        if not (legacy and key in LEGACY_CARDS):
            for line in opening:
                line["text"] = LINE_UPDATES.get(key, {}).get(line["text"], line["text"])
            existing_speakers = {line.get("npcId") for line in opening}
            new_lines = []
            for speaker, speech in ADDITIONS[key]:
                if speaker in ("narration", "player"):
                    new_lines.append({speaker: True, "text": speech})
                elif speaker in existing_speakers:
                    new_lines.append({"npcId": speaker, "text": speech})
            closing = -2 if key in CLOSING_EXCHANGES else -1
            opening[closing:closing] = new_lines
        # Unity overwrites existing list elements, so explicitly reset all line roles.
        for line in opening:
            line.setdefault("npcId", "")
            line.setdefault("player", False)
            line.setdefault("narration", False)
            line.setdefault("scene", 0)
    return events
